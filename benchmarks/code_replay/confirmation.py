"""Evaluator-only new-task qualification; never launches an agent."""
import argparse
from datetime import datetime, timezone
import json
from pathlib import Path

from atmem.evidence import EvidenceScope, EvidencePrincipal, EvidenceRole
from benchmarks.code_replay.atmem_bridge import ReplayEvidence
from benchmarks.code_replay.contracts import TaskManifest
from benchmarks.code_replay.freeze import digest
from benchmarks.code_replay.frozen import recover_report, digest_files, grader_tree, solution_tree
from benchmarks.code_replay.grade import tree_files, grade_files
from benchmarks.code_replay.prepare import git

DEFINITIONS = (
    ("fc6c7c4", 3211, "Preserve callable parameter conversion error messages",
     "When a callable parameter converter raises ValueError with an explanatory message, expose that message in the parameter-conversion error rather than replacing it with just the raw input. Preserve successful conversions and fallback behavior for an empty ValueError message."),
    ("c943271", 3256, "Preserve custom validation errors with hidden input",
     "With click.prompt(hide_input=True), custom type validation failures should display their explanatory error messages rather than always replacing them with the generic invalid-input message. Do not expose the hidden input value in error output. Preserve ordinary non-hidden prompts and retry behavior."),
    ("fe3ad76", 3653, "Honor color suppression in interactive prompts",
     "With CliRunner.invoke(color=False), styled text in click.confirm and click.prompt must not leak ANSI color codes into captured output. Preserve the expected prompt, user input and confirmation behavior, and preserve color when explicitly enabled where supported."),
    ("8a4ce84", 3677, "Validate style colors and preserve explicit black",
     "Validate click.style foreground and background color arguments. Valid named, indexed and RGB colors should keep working, invalid color arguments must fail clearly rather than produce invalid escape sequences, and the explicit black color argument 0 must not be mistaken for no color. Preserve other style attributes."),
    ("8c1a0a7", 3681, "Strip terminal ANSI sequences beyond Click-generated styles",
     "The ANSI stripping utility must recognize terminal ANSI escape sequences beyond the limited color sequences generated by Click itself, including CSI control sequences and OSC strings with their valid terminators. Preserve ordinary printable text and compatibility with Click style and formatting behavior. Do not remove text merely because it resembles an unfinished escape sequence."),
)


def main(*, definitions=DEFINITIONS, qualification_run="efficiency-confirmation-qualification",
         selection="five explicitly selected earlier Click changes; not a random or latest-five sample; 0039359 excluded before solver dispatch because unchanged upstream grader passes on parent"):
    p = argparse.ArgumentParser(description=__doc__)
    for name in ("checkout", "source", "output", "evidence-root"):
        p.add_argument("--" + name, type=Path, required=True)
    args = p.parse_args()
    if args.output.exists():
        raise ValueError("confirmation package already exists")
    base = json.loads(args.source.read_bytes())
    python, interpreter = Path(base["environment"]["python"]), Path(base["environment"]["interpreter"])
    scope = EvidenceScope("benchmark", "local-operator", "click-20261017")
    principal = EvidencePrincipal("local-benchmark-operator", EvidenceRole.ADMINISTRATOR, scope)
    vault = ReplayEvidence(args.evidence_root, vault_id="click-20261017", scope=scope)
    baseline = {"tests": "parent default suite plus changed upstream test files, immutable grading",
                "literal_tmp_exclusion": base["baseline"]["environment_exclusion"],
                "selection": selection,
                "solver_feedback": "none; no experience; no post-confirmation tuning"}
    vault.capture(run_id=qualification_run, kind="selection.frozen", principal=principal,
                  payload={"definitions": definitions, "baseline": baseline})
    tasks = []
    for order, (short, pull, title, requirements) in enumerate(definitions, 1):
        reference = git(args.checkout, "rev-parse", short + "^{commit}").decode().strip()
        parent = git(args.checkout, "rev-parse", reference + "^1").decode().strip()
        cutoff = datetime.fromisoformat(git(args.checkout, "show", "-s", "--format=%cI", reference).decode().strip()).astimezone(timezone.utc).isoformat()
        task = {"short": short, "pull": pull, "title": title, "requirements": requirements,
                "parent_commit": parent, "reference_commit": reference, "cutoff": cutoff}
        report = recover_report(task)
        observed_at = report["last_edited_at"] or report["report"]["created_at"]
        if datetime.fromisoformat(observed_at.replace("Z", "+00:00")) >= datetime.fromisoformat(cutoff):
            vault.capture(run_id=qualification_run, kind="qualification.blocked", principal=principal,
                          payload={"task": task, "report": report, "reason": "pre_solution_report_not_recovered"})
            raise ValueError("no pre-solution report for " + short)
        grader, outcomes = grader_tree(args.checkout, task), {}
        for variant in ("parent", "reference", "reference_repeat"):
            revision = parent if variant == "parent" else reference
            graded = grade_files(solution_tree(grader, tree_files(args.checkout, revision)), python=python,
                                 interpreter_root=interpreter, test_paths=("tests/",))
            outcomes[variant] = {**graded.summary(), "output": graded.output.decode(errors="replace")}
            print(json.dumps({"task": short, "variant": variant, **graded.summary()}), flush=True)
        retained = vault.capture(run_id=qualification_run, kind="grader.qualification", principal=principal,
                                payload={"task": task, "report": report, "outcomes": outcomes})
        if outcomes["parent"]["exit_code"] != 1 or outcomes["parent"]["environment_error"] or not all(outcomes[v]["passed"] for v in ("reference", "reference_repeat")):
            raise ValueError("new task qualification failed: " + short)
        manifest = {"format": TaskManifest.format, "task_id": "click-confirm-" + short, "order": order,
            "parent_commit": parent, "reference_commit": reference, "issue_version_sha256": digest(report),
            "requirements_sha256": digest(requirements), "source_sha256": digest_files(tree_files(args.checkout, parent)),
            "environment_sha256": digest(base["environment"]), "grader_sha256": digest_files(grader),
            "baseline_policy_sha256": digest(baseline), "license_ref": "click-bsd3-public-reports-private-evaluation",
            "requirements_at": observed_at, "solution_cutoff": cutoff, "parent_fails": True, "reference_passes": True}
        TaskManifest.from_dict(manifest)
        tasks.append({**task, "manifest": manifest, "qualification": retained})
    package = {"format": "atmem-code-efficiency-new-tasks-v1", "tasks": tasks, "baseline": baseline}
    vault.capture(run_id=qualification_run, kind="tasks.qualified", principal=principal, payload=package)
    with args.output.open("x") as stream:
        json.dump(package, stream, indent=2, sort_keys=True)
    print(json.dumps({"qualified_tasks": len(tasks), "sha256": digest(package)}), flush=True)


if __name__ == "__main__":
    main()
